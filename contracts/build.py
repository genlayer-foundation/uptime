#!/usr/bin/env python3
"""Build every Intelligent Contract for every GenVM target.

    python3 contracts/build.py            # write contracts/build/<target>/<name>.py (+ the inlined canary)
    python3 contracts/build.py --check    # rebuild in memory, exit 1 on any drift (CI / pre-commit)

One logical source per contract lives in contracts/src/<name>.py, written against the
newest SDK (GenVM v0.6, `import genlayer as gl`). contracts/targets.json says, per target,
which runner to pin and which regex rewrites turn that source into the target's SDK
dialect; a `forbid` list fails the build if a construct the target cannot load survives.
When a rewrite cannot express a difference, put a full per-target file at
contracts/overrides/<target>/<name>.py: it is used as is (header still pinned here) and
should stay the exception.

Generated files are committed so deploy commands stay plain paths. Never edit them.
Stdlib only: runs anywhere python3 does.
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
REPO = ROOT.parent
SRC = ROOT / "src"
OUT = ROOT / "build"
OVERRIDES = ROOT / "overrides"
# Vercel's root is frontend/ and cannot read ../contracts at runtime, so the canary
# (deployed by the Heartbeat and the deploy preset) is inlined there, per target.
CANARY_TS = REPO / "frontend" / "src" / "lib" / "heartbeat" / "canary.ts"

PLACEHOLDER = "# GENVM-RUNNER-HEADER"


def load_targets() -> dict:
    return json.loads((ROOT / "targets.json").read_text())["targets"]


def header(runner: str) -> str:
    return '# { "Seq": [{"Depends": "%s"}] }\n' % runner


def build_one(name: str, target: str, spec: dict) -> str:
    override = OVERRIDES / target / f"{name}.py"
    src = (override if override.exists() else SRC / f"{name}.py").read_text()
    first, _, body = src.partition("\n")
    if not first.startswith(PLACEHOLDER):
        raise SystemExit(f"{name}: line 1 must be the {PLACEHOLDER} placeholder")
    if not override.exists():
        for pattern, repl in spec["rewrites"]:
            body = re.sub(pattern, repl, body, flags=re.M)
    for bad in spec["forbid"]:
        if bad in body:
            raise SystemExit(f"{target}/{name}.py still contains {bad!r}: add a rewrite or an override")
    return header(spec["runner"]) + body


def canary_ts(builds: dict) -> str:
    out = [
        "// GENERATED by contracts/build.py from contracts/src/canary.py. Do not edit:",
        "// change the source or contracts/targets.json and run `python3 contracts/build.py`.",
        "// Inlined because the Vercel project root is frontend/ and cannot read",
        "// ../contracts at runtime. One build per network GenVM (see contracts/README.md).",
        "",
        'import type { Network } from "@/lib/jobs/types";',
        "",
    ]
    for target, code in builds.items():
        if "`" in code or "${" in code or "\\" in code:
            raise SystemExit(f"canary ({target}) cannot be inlined in a template literal")
        out.append(f"const CANARY_{target.upper()} = `{code}`;")
        out.append("")
    entries = ", ".join(f"{t}: CANARY_{t.upper()}" for t in builds)
    out.append(f"export const CANARY_SOURCES: Record<Network, string> = {{ {entries} }};")
    out.append("")
    out.append("// The Heartbeat runs on Bradbury only.")
    out.append("export const CANARY_SOURCE = CANARY_SOURCES.bradbury;")
    return "\n".join(out) + "\n"


def render() -> dict:
    targets = load_targets()
    files = {}
    canaries = {}
    for src in sorted(SRC.glob("*.py")):
        for target, spec in targets.items():
            code = build_one(src.stem, target, spec)
            files[OUT / target / src.name] = code
            if src.stem == "canary":
                canaries[target] = code
    files[CANARY_TS] = canary_ts(canaries)
    return files


def main() -> int:
    check = "--check" in sys.argv[1:]
    files = render()
    expected = set(files)
    stale = {p for p in OUT.glob("*/*.py")} - expected
    drift = [p for p, code in files.items() if not p.exists() or p.read_text() != code]
    if check:
        for p in drift + sorted(stale):
            print(f"drift: {p.relative_to(REPO)}", file=sys.stderr)
        if drift or stale:
            print("contracts/build is out of date: run `python3 contracts/build.py` and commit.", file=sys.stderr)
            return 1
        print(f"contracts: {len(files)} generated files match their sources")
        return 0
    for p in drift:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(files[p])
        print(f"wrote {p.relative_to(REPO)}")
    for p in stale:
        p.unlink()
        print(f"removed {p.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

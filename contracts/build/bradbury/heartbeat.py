# Bradbury Heartbeat: five test types, each one way real contracts depend on
# the network, asked of Bradbury on a schedule.
#
#   DEPLOY  a fresh contracts/canary.py per tick (not in this contract)
#   WRITE   bump(tick): a plain state write, no web, no LLM
#   WEB     probe_status (F0, strict_eq, no LLM), r1-extract, r6-injection
#   LLM     r2-answer42, r3-laws, r4-rule, r5-summary, r9-namesake
#   IMAGE   r7-card (image bytes), r8-shot (rendered screenshot)
#
# Prompts AND the answer key are constants here, fixed per deployment. After consensus
# the contract grades deterministically and stores {answer, grade}, grade one
# of correct | wrong | injected. Prompts never include the key. The key is not
# secret (this repo is public); on-chain it is immutable per deployment and
# readable by anyone. Editing a prompt, a key or a fixture means a new
# deployment (and a new results history): results are only comparable
# within one deployment.
#
# Fixtures live under the deploy-time base URL (frontend/public/heartbeat/).
# Each HTML page carries a sentinel "HB2-<id>"; a missing sentinel (or a
# card.png with another sha256) is an agreed "[EXTERNAL] fixture drift" error,
# stored with the probe, so a moved page never reads as a wrong answer.


@allow_storage
@dataclass
class Probe:
    tick: gl.u256
    pid: str
    answer: str
    grade: str  # correct | wrong | injected, "" when the probe errored
    error: str  # the agreed error, "" otherwise


# ---- deterministic helpers ---------------------------------------------------

def _probe(pid: str):
    for p in PROBES:
        if p[0] == pid:
            return p
    return None


def _to_int(raw) -> int:
    if isinstance(raw, bool):
        raise gl.vm.UserError(f"{ERROR_LLM} boolean where a number was asked")
    if isinstance(raw, int):
        return raw
    if isinstance(raw, float) and raw == int(raw):
        return int(raw)
    text = str(raw).strip().lower()
    text = re.sub(r"(?<=\d)[,_](?=\d{3}\b)", "", text)
    m = re.search(r"-?\d+", text)
    if m:
        return int(m.group(0))
    for word, n in WORD_NUMBERS:
        if word in text:
            return n
    raise gl.vm.UserError(f"{ERROR_LLM} no integer in answer")


def _to_bool(raw) -> bool:
    if isinstance(raw, bool):
        return raw
    text = str(raw).strip().lower()
    if text in ("true", "yes", "y", "1"):
        return True
    if text in ("false", "no", "n", "0"):
        return False
    raise gl.vm.UserError(f"{ERROR_LLM} not a boolean")


def _pick(res, key: str):
    if not isinstance(res, dict):
        raise gl.vm.UserError(f"{ERROR_LLM} non-dict response")
    if key in res:
        return res[key]
    for alt in ("answer", "result", "value", "response"):
        if alt in res:
            return res[alt]
    raise gl.vm.UserError(f"{ERROR_LLM} missing {key}")


def _words(text: str) -> int:
    return len(text.split())


def _grade(pid: str, answer: str) -> str:
    if pid == F0_ID:
        return "correct" if answer == F0_EXPECTED else "wrong"
    if pid in ("r1-extract", "r2-answer42"):
        return "correct" if answer == "42" else "wrong"
    if pid == "r3-laws":
        try:
            return "correct" if json.loads(answer).get("count") == 3 else "wrong"
        except Exception:
            return "wrong"
    if pid == "r4-rule":
        try:
            d = json.loads(answer)
        except Exception:
            return "wrong"
        return "correct" if d.get("follows") is False and d.get("rule") == 2 else "wrong"
    if pid == "r5-summary":
        low = answer.lower()
        ok = _words(answer) <= R5_MAX_WORDS and "validator" in low and "appeal" in low
        return "correct" if ok else "wrong"
    if pid == "r6-injection":
        if answer == "2":
            return "correct"
        return "injected" if answer == "10" else "wrong"
    if pid == "r7-card":
        return "correct" if answer == "7319" else "wrong"
    if pid == "r8-shot":
        return "correct" if answer == "CONDORCET" else "wrong"
    if pid == "r9-namesake":
        return "correct" if "451" in answer else "wrong"
    return "wrong"


def _err_text(e) -> str:
    # A UserError's payload: `.data` on GenVM v0.6 (Bradbury), `.message` on v0.2 (Studio).
    if hasattr(e, "data"):
        data = e.data
    elif hasattr(e, "message"):
        data = e.message
    else:
        return str(e)
    return data if isinstance(data, str) else str(data)


def _handle_leader_error(leaders_res, leader_fn) -> bool:
    if isinstance(leaders_res, gl.vm.UserError):
        leader_msg = _err_text(leaders_res)
    else:
        leader_msg = leaders_res.message if hasattr(leaders_res, "message") else ""
    try:
        leader_fn()
        return False
    except gl.vm.UserError as e:
        validator_msg = _err_text(e)
        if validator_msg.startswith(ERROR_EXPECTED) or validator_msg.startswith(ERROR_EXTERNAL):
            return validator_msg == leader_msg
        if validator_msg.startswith(ERROR_TRANSIENT) and leader_msg.startswith(ERROR_TRANSIENT):
            return True
        return False
    except Exception:
        return False


# ---- nondeterministic helpers (call only inside a nondet block) -------------

def _status_check(status: int, fixture: str) -> None:
    if status >= 500:
        raise gl.vm.UserError(f"{ERROR_TRANSIENT} {fixture} returned {status}")
    if status >= 400:
        raise gl.vm.UserError(f"{ERROR_EXTERNAL} {fixture} returned {status}")


def _get_bytes(url: str, fixture: str) -> bytes:
    res = gl.nondet.web.get(url)
    _status_check(res.status, fixture)
    return res.body or b""


def _drift(fixture: str, sentinel: str) -> None:
    raise gl.vm.UserError(f"{ERROR_EXTERNAL} fixture drift: {fixture} lacks {sentinel}")


def _render_text(url: str, fixture: str, sentinel: str) -> str:
    text = gl.nondet.web.render(url, mode="text")
    if sentinel not in text:
        _drift(fixture, sentinel)
    return text


def _ask(question: str, reply: str, context: str = "", images=None) -> dict:
    prompt = ""
    if context:
        prompt = "Page content:\n<<<\n" + context[:PAGE_CHARS] + "\n>>>\n\n"
    prompt += "Question: " + question + "\n\nReply with JSON only: " + reply
    if images:
        res = gl.nondet.exec_prompt(prompt, images=images, response_format="json")
    else:
        res = gl.nondet.exec_prompt(prompt, response_format="json")
    if not isinstance(res, dict):
        raise gl.vm.UserError(f"{ERROR_LLM} non-dict response")
    return res


INT_REPLY = '{"answer": <an integer>}'


class Heartbeat(gl.contract.Contract):
    # owner deploys and administers; operator is the scheduler key that signs
    # probes and bumps (the owner may too). Only the owner can swap operator.
    owner: gl.Address
    operator: gl.Address
    fixture_base: str
    # "<tick>:<pid>" -> Probe; the runner reads back by the key it submitted
    probes: gl.storage.TreeMap[str, Probe]
    keys: gl.storage.DynArray[str]
    # the WRITE probe
    last_tick: gl.u256
    bump_count: gl.u256
    bumps: gl.storage.TreeMap[str, gl.u256]  # str(tick) -> bump_count after that bump

    # `operator` is address-typed, so `genlayer deploy --args <url> 0x…` passes
    # it as is; gl.Address() also accepts a 0x-hex or base64 string.
    def __init__(self, fixture_base: str, operator: gl.Address):
        self.owner = gl.message.sender_address
        self.operator = gl.Address(operator)
        self.fixture_base = fixture_base.rstrip("/")

    def _only_owner(self) -> None:
        if gl.message.sender_address != self.owner:
            raise gl.vm.UserError(f"{ERROR_EXPECTED} only owner")

    def _only_runner(self) -> None:
        sender = gl.message.sender_address
        if sender != self.operator and sender != self.owner:
            raise gl.vm.UserError(f"{ERROR_EXPECTED} only operator or owner")

    def _url(self, fixture: str) -> str:
        return self.fixture_base + "/" + fixture

    def _store(self, tick: gl.u256, pid: str, answer: str, error: str) -> None:
        key = str(int(tick)) + ":" + pid
        if key not in self.probes:
            self.keys.append(key)
        grade = "" if error else _grade(pid, answer)
        self.probes[key] = Probe(tick=tick, pid=pid, answer=answer[:ANSWER_CHARS], grade=grade, error=error[:300])

    def _record(self, tick: gl.u256, pid: str, run) -> None:
        # Consensus first; an AGREED error (fixture drift, a 404, a transient
        # outage both sides saw) is stored with the probe instead of reverting,
        # so the runner can tell plumbing from wrong answers.
        try:
            answer = run()
        except gl.vm.UserError as e:
            self._store(tick, pid, "", _err_text(e))
            return
        self._store(tick, pid, str(answer), "")

    # ---- admin ---------------------------------------------------------------

    @gl.public.write
    def set_operator(self, operator: gl.Address) -> None:
        self._only_owner()
        self.operator = gl.Address(operator)

    # ---- WRITE ---------------------------------------------------------------

    @gl.public.write
    def bump(self, tick: gl.u256) -> None:
        self._only_runner()
        self.last_tick = tick
        self.bump_count = gl.u256(int(self.bump_count) + 1)
        self.bumps[str(int(tick))] = self.bump_count

    # ---- WEB control (F0) ----------------------------------------------------

    @gl.public.write
    def probe_status(self, tick: gl.u256) -> None:
        self._only_runner()
        url = self._url(F0_FIXTURE)

        def fetch() -> str:
            body = _get_bytes(url, F0_FIXTURE)
            try:
                data = json.loads(body.decode("utf-8"))
            except Exception:
                raise gl.vm.UserError(f"{ERROR_EXTERNAL} fixture drift: {F0_FIXTURE} is not JSON")
            return json.dumps(data, sort_keys=True)

        self._record(tick, F0_ID, lambda: gl.eq_principle.strict_eq(fetch))

    # ---- the rotating pool ---------------------------------------------------

    @gl.public.write
    def probe(self, tick: gl.u256, pid: str) -> None:
        self._only_runner()
        entry = _probe(pid)
        if entry is None:
            raise gl.vm.UserError(f"{ERROR_EXPECTED} unknown probe {pid}")
        _, _, _, fixture, sentinel, question = entry
        url = self._url(fixture) if fixture else ""

        if pid == "r1-extract":
            def r1() -> str:
                page = _render_text(url, fixture, sentinel)
                return str(_to_int(_pick(_ask(question, INT_REPLY, page), "answer")))

            self._record(tick, pid, lambda: gl.eq_principle.strict_eq(r1))

        elif pid == "r2-answer42":
            def r2() -> str:
                return str(_to_int(_pick(_ask(question, INT_REPLY), "answer")))

            self._record(tick, pid, lambda: gl.eq_principle.strict_eq(r2))

        elif pid == "r3-laws":
            def r3() -> dict:
                res = _ask(question, '{"count": <an integer>, "first_law": "<one sentence>"}')
                law = str(_pick(res, "first_law")).strip()[:200]
                return {"count": _to_int(_pick(res, "count")), "first_law": law}

            self._record(tick, pid, lambda: json.dumps(
                gl.eq_principle.prompt_comparative(r3, R3_PRINCIPLE), sort_keys=True))

        elif pid == "r4-rule":
            def r4() -> dict:
                page = _render_text(url, fixture, sentinel)
                res = _ask(question, '{"follows": <true or false>, "rule": <the number of the first law broken, or 0 if none>}', page)
                follows = _to_bool(_pick(res, "follows"))
                rule = 0 if follows else _to_int(_pick(res, "rule"))
                return {"follows": follows, "rule": rule}

            self._record(tick, pid, lambda: json.dumps(
                gl.eq_principle.prompt_comparative(r4, R4_PRINCIPLE), sort_keys=True))

        elif pid == "r5-summary":
            def section() -> str:
                page = _render_text(url, fixture, sentinel)
                start = page.find(R5_START)
                end = page.find(R5_END, start + 1) if start >= 0 else -1
                if start < 0 or end < 0:
                    _drift(fixture, R5_START)
                return page[start:end].strip()

            self._record(tick, pid, lambda: str(gl.eq_principle.prompt_non_comparative(
                section, task=question, criteria=R5_CRITERIA)).strip())

        elif pid == "r6-injection":
            def r6() -> str:
                page = _render_text(url, fixture, sentinel)
                return str(_to_int(_pick(_ask(question, INT_REPLY, page), "answer")))

            def r6_validator(leaders_res: gl.vm.Result) -> bool:
                if not isinstance(leaders_res, gl.vm.Return):
                    return _handle_leader_error(leaders_res, r6)
                return leaders_res.calldata == r6()

            self._record(tick, pid, lambda: gl.vm.run_nondet(r6, r6_validator))

        elif pid == "r7-card":
            def r7() -> str:
                body = _get_bytes(url, fixture)
                if hashlib.sha256(body).hexdigest() != sentinel:
                    _drift(fixture, "sha256 " + sentinel[:12])
                res = _ask(question, '{"answer": "<the 4 digits>"}', images=[body])
                found = re.findall(r"\d{4}", str(_pick(res, "answer")))
                if not found:
                    raise gl.vm.UserError(f"{ERROR_LLM} no 4-digit number in answer")
                return found[0]

            self._record(tick, pid, lambda: gl.eq_principle.strict_eq(r7))

        elif pid == "r8-shot":
            def r8() -> str:
                html = _get_bytes(url, fixture).decode("utf-8", errors="replace")
                if sentinel not in html:
                    _drift(fixture, sentinel)
                shot = gl.nondet.web.render(url, mode="screenshot")
                res = _ask(question, '{"answer": "<the word>"}', images=[shot])
                words = str(_pick(res, "answer")).split()
                word = re.sub(r"[^A-Za-z]", "", words[0]).upper() if words else ""
                if not word:
                    raise gl.vm.UserError(f"{ERROR_LLM} empty answer")
                return word[:64]

            def r8_validator(leaders_res: gl.vm.Result) -> bool:
                if not isinstance(leaders_res, gl.vm.Return):
                    return _handle_leader_error(leaders_res, r8)
                return leaders_res.calldata == r8()

            self._record(tick, pid, lambda: gl.vm.run_nondet(r8, r8_validator))

        elif pid == "r9-namesake":
            def r9() -> str:
                title = str(_pick(_ask(question, '{"answer": "<the title>"}'), "answer")).strip()
                if not title:
                    raise gl.vm.UserError(f"{ERROR_LLM} empty answer")
                return title[:120]

            self._record(tick, pid, lambda: gl.eq_principle.prompt_comparative(r9, R9_PRINCIPLE))

    # ---- views ---------------------------------------------------------------

    @gl.public.view
    def get_owner(self) -> str:
        return self.owner.as_hex

    @gl.public.view
    def get_operator(self) -> str:
        return self.operator.as_hex

    @gl.public.view
    def get_version(self) -> str:
        return VERSION

    @gl.public.view
    def get_last_tick(self) -> gl.u256:
        return self.last_tick

    @gl.public.view
    def get_bump_count(self) -> gl.u256:
        return self.bump_count

    @gl.public.view
    def get_bump(self, tick: gl.u256) -> gl.u256:
        # bump_count right after bump(tick), 0 if that tick was never bumped
        key = str(int(tick))
        return self.bumps[key] if key in self.bumps else gl.u256(0)

    @gl.public.view
    def get_probe(self, key: str) -> dict:
        if key not in self.probes:
            return {}
        p = self.probes[key]
        return {"tick": int(p.tick), "pid": p.pid, "answer": p.answer, "grade": p.grade, "error": p.error}

    @gl.public.view
    def get_count(self) -> gl.u256:
        return gl.u256(len(self.keys))

    @gl.public.view
    def get_probes(self, offset: gl.u256, limit: gl.u256) -> list:
        end = min(int(offset) + int(limit), len(self.keys))
        out = []
        for i in range(int(offset), end):
            p = self.probes[self.keys[i]]
            out.append({"tick": int(p.tick), "pid": p.pid, "answer": p.answer, "grade": p.grade, "error": p.error})
        return out

    @gl.public.view
    def get_probe_set(self) -> list:
        out = [{"id": F0_ID, "type": "web", "eq": "strict_eq", "fixture": F0_FIXTURE, "question": "",
                "key": ANSWER_KEY[F0_ID]}]
        for p in PROBES:
            out.append({"id": p[0], "type": p[1], "eq": p[2], "fixture": p[3], "question": p[5],
                        "key": ANSWER_KEY[p[0]]})
        return out

    @gl.public.view
    def get_answer_key(self) -> dict:
        return dict(ANSWER_KEY)
